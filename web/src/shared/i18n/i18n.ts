function getInitialLanguage() {
  const storedLanguage = window.localStorage.getItem('store-language')
  if (storedLanguage === 'es' || storedLanguage === 'en-US') return storedLanguage
  return navigator.language.toLowerCase().startsWith('es') ? 'es' : 'en-US'
}

i18n.on('languageChanged', (language) => {
  if (language === 'es' || language === 'en-US') {
    window.localStorage.setItem('store-language', language)
  }
})

